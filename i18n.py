_CURRENT_LANG = None

def get_current_language():
    global _CURRENT_LANG
    if _CURRENT_LANG is None:
        _CURRENT_LANG = get_language()
    return _CURRENT_LANG

def set_current_language(lang):
    global _CURRENT_LANG
    if lang in ("de", "en"):
        _CURRENT_LANG = lang
        set_language(lang)
        return True
    return False

def t(key, default=None, **kwargs):
    """
    Returns translated string for given key in the current language.
    Falls back to German if key is missing in English, or to default if provided.
    """
    lang = get_current_language()
    val = TRANSLATIONS.get(lang, {}).get(key)
    if val is None:
        val = TRANSLATIONS.get("de", {}).get(key)
    if val is None:
        val = default if default is not None else key
    
    if kwargs:
        try:
            return val.format(**kwargs)
        except Exception:
            return val
    return val
